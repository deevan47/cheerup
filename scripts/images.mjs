// Builds the responsive variants of every product photo, then writes the size
// manifest that lib/img.js reads.
//
// Run it by hand after adding or replacing a photo in public/photos:
//     npm run images
//
// Why it exists: the originals were served at full size into 72px thumbnails and
// 379px cards, as JPEG only, with no width or height on the <img>, so phones
// downloaded far more than they showed and the page jumped as each one landed.
//
// It never upscales. A photo whose original is 332px wide gets no 800px variant,
// because inventing pixels only makes a bigger file. The three small originals
// (phone cases, the big Polaroid, the framed print) are the reason the manifest
// below has gaps; replacing them with 1200px+ originals and re-running this is
// all that is needed to fill them in.
import { execFileSync } from 'node:child_process';
import { readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const DIR = 'public/photos';
const WIDTHS = [160, 320, 480, 800, 1200];

const magick = (args) => execFileSync('magick', args, { encoding: 'utf8' }).trim();

const files = readdirSync(DIR).filter((f) => /\.jpe?g$/i.test(f)).sort();
const manifest = {};

for (const file of files) {
  const path = join(DIR, file);
  const [w, h] = magick([path, '-format', '%w %h', 'info:']).split(' ').map(Number);
  const base = file.replace(/\.jpe?g$/i, '');
  const widths = WIDTHS.filter((x) => x < w);

  // WebP at each width that the original can actually fill, plus the full size
  for (const x of widths) {
    magick([path, '-resize', `${x}x`, '-quality', '78', '-strip', join(DIR, `${base}-${x}.webp`)]);
  }
  magick([path, '-quality', '80', '-strip', join(DIR, `${base}.webp`)]);

  manifest[`photos/${file}`] = { w, h, widths: [...widths, w] };
  console.log(`${file}  ${w}x${h}  ->  ${[...widths, w].join(', ')}`);
}

const body = `// GENERATED by scripts/images.mjs. Do not edit by hand; run \`npm run images\`.
// For each photo: its real pixel size, and the widths a WebP variant exists at.
export const IMAGES = ${JSON.stringify(manifest, null, 2)};
`;
writeFileSync('src/data/images.js', body);
console.log(`\nwrote src/data/images.js (${files.length} photos)`);
